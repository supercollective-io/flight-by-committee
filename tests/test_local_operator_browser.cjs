// Run against a disposable operator root; launch/status/stop are synthetic here.
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const url = process.env.FLIGHT_OPERATOR_URL;
  assert(url, 'Set FLIGHT_OPERATOR_URL to the local URL including its fragment.');
  const output = process.env.FLIGHT_OPERATOR_SCREENSHOTS || 'test-results/operator-browser';
  await fs.mkdir(output, {recursive:true});
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[];page.on('pageerror', error=>errors.push(error.message));
    page.on('dialog', dialog=>dialog.accept());
    let offline=false;
    let state={phase:'idle',active:false,message:'No flight launched yet.'}, launched;
    await page.route('**/api/status', route=>route.fulfill(offline ? {status:503,body:'Unavailable'} : {json:state}));
    await page.route('**/api/launch', async route=>{
      launched=route.request().postDataJSON();
      state={phase:'loading',active:true,name:launched.name,description:launched.profile.description,message:'Waiting for simulator connection and aircraft readiness…'};
      await route.fulfill({json:state});
    });
    await page.route('**/api/stop', async route=>{
      state={phase:'stopped',active:false,message:'Flight stopped. Choose settings and launch again.'};
      await route.fulfill({json:state});
    });
    await page.goto(url);
    await page.locator('#settings').waitFor({state:'visible'});
    assert.equal(await page.locator('#aircraft').inputValue(),'ufo');
    assert(!page.url().includes('#'),'Token must leave the address bar');
    await page.screenshot({path:output+'/desktop.png',fullPage:true});
    await page.getByRole('button',{name:'Duplicate',exact:true}).click();
    const name='browser-check-'+Date.now();
    await page.locator('#name').fill(name);
    await page.locator('#description').fill('Synthetic browser profile');
    await page.locator('#altitude_m').fill('1450');
    await page.locator('#latitude_deg').fill('48.8');
    assert.equal(await page.locator('#location').inputValue(),'');
    await page.getByRole('button',{name:'Save local profile',exact:true}).click();
    await page.waitForFunction(()=>document.getElementById('feedback').textContent.startsWith('Local profile saved'));
    await page.reload();
    await page.getByRole('button',{name:new RegExp(name)}).click();
    await page.waitForFunction(()=>document.getElementById('altitude_m').value==='1450');
    assert.equal(await page.locator('#latitude_deg').inputValue(),'48.8');
    await page.getByRole('button',{name:'Launch these settings',exact:true}).click();
    await page.waitForFunction(()=>document.getElementById('phase').textContent==='Loading aircraft');
    assert.equal(launched.profile.flight.altitude_m,1450);
    assert(await page.locator('#launch').isDisabled());
    await page.locator('#altitude_m').fill('1600');
    assert.equal(launched.profile.flight.altitude_m,1450);
    await page.getByRole('button',{name:'Stop flight',exact:true}).click();
    await page.waitForFunction(()=>document.getElementById('phase').textContent==='Stopped');
    assert(await page.locator('#launch').isEnabled());
    await page.getByRole('button',{name:'New profile',exact:true}).click();
    assert.equal(await page.locator('#latitude_deg').inputValue(),'');
    assert.equal(await page.locator('#longitude_deg').inputValue(),'');
    await page.locator('#name').fill(name+'-ground');
    await page.locator('#location').selectOption('schiphol-ground');
    assert(await page.locator('#altitude-field').isHidden());
    await page.getByRole('button',{name:'Save local profile',exact:true}).click();
    await page.waitForFunction(()=>document.getElementById('feedback').textContent.startsWith('Local profile saved'));
    await page.setViewportSize({width:390,height:844});
    await page.evaluate(()=>scrollTo(0,0));
    assert(await page.locator('.profile').evaluateAll(items=>items.every(item=>item.scrollHeight<=item.clientHeight+2)),'Profile labels must not overlap');
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No horizontal overflow');
    await page.locator('#name').focus();await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(()=>document.activeElement.id),'description');
    await page.route('**/api/launch',route=>route.fulfill({status:400,json:{error:'Synthetic missing aircraft. Check installation paths.'}}));
    await page.locator('#launch').click();
    await page.waitForFunction(()=>document.getElementById('feedback').dataset.error==='true');
    assert.match(await page.locator('#feedback').textContent(),/missing aircraft/);
    assert(await page.locator('#launch').isEnabled());
    await page.getByRole('button',{name:/^karlsruhe-747-landing/}).click();
    await page.waitForFunction(()=>document.getElementById('aircraft').value==='747-400');
    state={phase:'ready',active:true,name:'karlsruhe-747-landing',description:'Land the Boeing 747-400 at Karlsruhe/Baden-Baden, runway 03',message:'Aircraft reports ready. Pause and reset in FlightGear.'};
    await page.waitForFunction(()=>document.getElementById('phase').textContent==='Aircraft ready');
    await page.locator('#editor-title').click();
    await page.evaluate(()=>scrollTo(0,0));
    await page.screenshot({path:output+'/mobile.png',fullPage:true});
    await page.screenshot({path:output+'/mobile-viewport.png'});
    const stopBox = await page.locator('#stop-mobile').boundingBox();
    assert(stopBox.y>=0 && stopBox.y+stopBox.height<=844,'Mobile stop remains in the viewport');
    offline=true;
    await page.waitForFunction(()=>document.getElementById('phase').textContent==='Status unavailable');
    assert(await page.locator('#stop-mobile').isDisabled());
    offline=false;
    await page.waitForFunction(()=>document.getElementById('phase').textContent==='Aircraft ready');
    await page.locator('#stop-mobile').click();
    await page.waitForFunction(()=>document.getElementById('phase').textContent==='Stopped');
    assert.deepEqual(errors,[]);
    console.log('Operator browser: profile selection, duplication, persistence, coordinates, ground start, launch/stop, errors, keyboard and responsive layout passed.');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
